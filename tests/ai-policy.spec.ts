import {test,expect} from '@playwright/test';
import {isAnchoredSuggestion,passesObviousClaimCheck} from '../app/api/discover-skills/policy';
test('professional qualities are allowed while concrete unsupported claims are withheld',()=>{
 expect(passesObviousClaimCheck('Reliable worker maintaining clean, orderly spaces','I cleaned rooms and changed linens.')).toBe(true);
 expect(passesObviousClaimCheck('Full-time childcare','I cared for my child at home.')).toBe(false);
 expect(passesObviousClaimCheck('Fluent in English and Spanish','I speak English and Spanish.')).toBe(false);
 expect(passesObviousClaimCheck('Reliable volunteer','I organized donated shoes.')).toBe(false);
 expect(passesObviousClaimCheck('Reliable volunteer','I volunteered sorting clothes.')).toBe(true);
 expect(passesObviousClaimCheck('Certified forklift operator','I am not certified.')).toBe(false);
 expect(passesObviousClaimCheck('Improved productivity by 50%','I cleaned rooms.')).toBe(false);
 expect(passesObviousClaimCheck('Event setup and cleanup','I helped stack chairs after a school event.')).toBe(false);
 expect(passesObviousClaimCheck('Reliable worker who kept rooms clean','I cleaned rooms.')).toBe(true);
 expect(passesObviousClaimCheck('Assisted with inventory tracking','I helped count boxes.')).toBe(false);
 expect(passesObviousClaimCheck('Sorted donated shoes for distribution','I organized donated shoes.')).toBe(false);
 expect(passesObviousClaimCheck('Provided daily care','I cared for my child.')).toBe(false);
 expect(passesObviousClaimCheck('Provided day-to-day care','I cared for my child at home.')).toBe(false);
 expect(passesObviousClaimCheck('Regular floor sweeping','I swept floors.')).toBe(false);
 expect(passesObviousClaimCheck('Experience maintaining clean floors through regular sweeping','I only swept floors.')).toBe(false);
 expect(passesObviousClaimCheck('Tended vegetables','I planted vegetables.')).toBe(false);
 expect(passesObviousClaimCheck('Organized pencils and other supplies','I organized pencils.')).toBe(false);
 expect(passesObviousClaimCheck('Learned safety basics','I attended a forklift class.')).toBe(false);
 expect(passesObviousClaimCheck('Commitment to continued education','I earned my GED last spring.')).toBe(false);
 expect(passesObviousClaimCheck('Lifting heavy items','I moved bags of donated food.')).toBe(false);
 expect(passesObviousClaimCheck("Looking after a neighbor's home",'I checked a neighbor’s mail.')).toBe(false);
 expect(passesObviousClaimCheck('Yard maintenance','I mowed my aunt’s lawn one weekend.')).toBe(false);
 expect(passesObviousClaimCheck('Enjoys preparing meals','I followed a recipe for soup.')).toBe(false);
 expect(passesObviousClaimCheck('Studied independently for a GED','I studied for a GED.')).toBe(false);
 expect(passesObviousClaimCheck('Moved bags of donated food','I moved bags of donated food.')).toBe(true);
 expect(passesObviousClaimCheck('Conversational Portuguese','I speak a little Portuguese.')).toBe(false);
 expect(passesObviousClaimCheck('Hablo inglés y español','I speak English and Spanish.')).toBe(false);
 expect(passesObviousClaimCheck('Limpieza de habitaciones','Limpié habitaciones.')).toBe(true);
 expect(passesObviousClaimCheck('Cleaning and organizing storage areas','I wiped shelves and swept a storage room.')).toBe(false);
 expect(isAnchoredSuggestion('Reliable worker with experience cleaning rooms','I cleaned rooms.','I cleaned rooms.')).toBe(true);
 expect(isAnchoredSuggestion('Reliable worker with experience cleaning rooms','I cleaned rooms.','I swept floors.')).toBe(false);
});
